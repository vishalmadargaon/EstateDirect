function daysAgoIso(daysAgo: number, hourOffset = 10): string {
  const now = Date.now();
  const d = new Date(now - daysAgo * 24 * 60 * 60 * 1000 - hourOffset * 3600 * 1000);
  return d.toISOString();
}

